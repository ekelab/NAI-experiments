"""
The R² of a SLDBench run, recomputed by SLDBench's own evaluator
(sldbench/upstream/evaluator.py, fetched by reproduce/fetch_data.sh, unchanged)
- an independent check of sldbench.py's arithmetic.

Each chosen form (chosen_<tag>.json) becomes a program in SLDBench's
format, as their agents write them: fit_scaling_law(X, y) → params and
scaling_law_func(X, params) → predictions (for domain_mixture, five targets:
five forms, their constants concatenated). The evaluator imports it, fits it
per group on the training split and scores the test split. The one
substitution: upstream's data_loader reads the Hugging Face hub through the
`datasets` package; here a loader with the same interface reads the local
copies, which sld_verify_data.py checked against the hub value for value.

    python sld_verify_r2.py --chosen ../results/v9/chosen_p123-all-mean.json --csv ../results/v9/nai_sldbench_p123-all-mean.csv
"""
import argparse, collections, importlib.util, json, os, sys, types

import numpy as np

import sldbench as S

HERE = os.path.dirname(os.path.abspath(__file__))

PROGRAM = '''# A NAI form for SLDBench - generated by harness/sld_verify_r2.py
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), {bench!r}))
import numpy as np
import sldfit

FORMS = [sldfit.Form(t, {nvars}, lv, ly) for t, lv, ly in {forms!r}]


def fit_scaling_law(data_points, loss_values):
    X = [tuple(float(v) for v in row) for row in np.asarray(data_points)]
    Y = np.asarray(loss_values, dtype=float)
    Y = Y.reshape(len(X), -1)
    params = []
    for j, f in enumerate(FORMS):
        c, e = sldfit.fit(f, X, list(Y[:, j]), f.init, iters=200)
        params += list(c)
    return np.array(params)


def scaling_law_func(data_points, params):
    X = [tuple(float(v) for v in row) for row in np.asarray(data_points)]
    out, k = [], 0
    for f in FORMS:
        out.append(f(X, list(params[k:k + f.k])))
        k += f.k
    out = np.array(out, dtype=float).T
    return out[:, 0] if out.shape[1] == 1 else out
'''


def local_loader(app_name, train=True):
    """upstream data_loader.load_data's interface, on the verified local copies."""
    feats, targets, _, _ = S.TASKS[app_name]
    groups = S.load(app_name, "train" if train else "test")
    out = {}
    for g in sorted(groups):
        rows = groups[g]
        X = np.stack([np.array([r[f] for r in rows]) for f in feats], axis=1)
        Y = np.stack([np.array([r[t] for r in rows]) for t in targets], axis=1)
        out[g] = (X, Y.squeeze(axis=1) if Y.shape[1] == 1 else Y)
    return out


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    ap = argparse.ArgumentParser()
    ap.add_argument("--chosen", required=True)
    ap.add_argument("--csv", default="")      # our own table, to compare with
    a = ap.parse_args()
    sys.modules["data_loader"] = types.SimpleNamespace(load_data=local_loader)
    spec = importlib.util.spec_from_file_location("evaluator", os.path.join(HERE, "sldbench", "upstream", "evaluator.py"))
    ev = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(ev)
    ours = {}
    if a.csv and os.path.exists(a.csv):
        import csv
        ours = {r["task"]: float(r["r2"]) for r in csv.DictReader(open(a.csv, encoding="utf-8"))}
    chosen = json.load(open(a.chosen, encoding="utf-8"))
    work = os.path.join(os.path.dirname(os.path.abspath(a.chosen)), "verify_programs")
    os.makedirs(work, exist_ok=True)
    total = []
    for task, entries in chosen.items():
        feats, targets, _, _ = S.TASKS[task]
        by_target = {e["target"]: (e["form"], tuple(e["logvars"]), bool(e.get("logy", False))) for e in entries}
        forms = [by_target[t] for t in targets]
        path = os.path.join(work, task + ".py")
        open(path, "w", encoding="utf-8").write(PROGRAM.format(bench=os.path.relpath(HERE, work).replace(os.sep, "/"), nvars=len(feats), forms=forms))
        os.environ["EVAL_TASK_NAME"] = task
        res = ev.evaluate(path, verbose=False, use_test_data=True)
        r2 = res.get("r2", float("nan"))
        total.append(r2)
        o = ours.get(task)
        print("%-30s upstream evaluator R2 %9.4f   ours %s%s" % (
            task, r2, "%9.4f" % o if o is not None else "   -",
            "" if o is None or abs(o - r2) < 1e-5 else "   ← DIFFERENT"), flush=True)   # the CSV keeps 6 decimals
        if res.get("error"):
            print("    error:", res["error"])
    print("mean over %d tasks: %.4f" % (len(total), sum(total) / len(total)))


if __name__ == "__main__":
    main()
